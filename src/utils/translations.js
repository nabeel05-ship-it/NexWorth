/**
 * Helper to fetch translation with fallback to English and parameter interpolation
 * Example: getTranslation('exp_toast_added', 'hi', { name: 'Swiggy', amount: '450' })
 */
export function getTranslation(key, lang = 'en', params = {}) {
  const currentLang = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = currentLang && currentLang[key] !== undefined
    ? currentLang[key]
    : (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);

  if (typeof text === 'string' && params && typeof params === 'object') {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), val);
    });
  }
  return text;
}

/**
 * Formats a currency number in INR with locale-aware groupings
 */
export function formatCurrency(amount, lang = 'en') {
  const locale = lang === 'hi' ? 'hi-IN' : lang === 'kn' ? 'kn-IN' : 'en-IN';
  return `₹${Number(amount || 0).toLocaleString(locale)}`;
}

/**
 * Formats a date using the appropriate locale
 */
export function formatDate(date, lang = 'en', options = { day: 'numeric', month: 'short', year: 'numeric' }) {
  const locale = lang === 'hi' ? 'hi-IN' : lang === 'kn' ? 'kn-IN' : 'en-IN';
  try {
    const d = typeof date === 'string' ? new Date(date) : date;
    if (isNaN(d.getTime())) return String(date);
    return d.toLocaleDateString(locale, options);
  } catch (e) {
    return String(date);
  }
}

